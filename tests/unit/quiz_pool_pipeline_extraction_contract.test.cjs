'use strict';
// Exact-source extraction contract: the module is substituted at one marker and the release build must remain byte-identical.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const fragmentPath = path.join(root, 'src/scripts/script_004.htmlpart');
const modulePath = path.join(root, 'src/modules/quiz_pool_pipeline.htmlpart');
const fragment = fs.readFileSync(fragmentPath, 'utf8');
const moduleBytes = fs.readFileSync(modulePath);
const moduleText = moduleBytes.toString('utf8');
const marker = '<!-- AMQ_SPLIT_MODULE:quiz_pool_pipeline -->';
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'reports/FRAGMENT_MANIFEST.json'), 'utf8'));
const fragmentRecord = manifest.fragments.find(x => x.path === 'src/scripts/script_004.htmlpart');
const moduleRecord = manifest.modules.find(x => x.name === 'quiz_pool_pipeline');
assert.ok(fragmentRecord, 'script_004 fragment remains registered');
assert.ok(moduleRecord, 'candidate-pool module is registered');
assert.equal(fragment.split(marker).length - 1, 1, 'module insertion marker occurs exactly once');
assert.equal(moduleRecord.marker, marker, 'manifest marker matches source marker');
assert.equal(moduleRecord.insertion_fragment, 'src/scripts/script_004.htmlpart', 'module is inserted in original fragment');
assert.equal(moduleRecord.runtime_contract, 'exact source bytes moved from script_004; same IIFE/classic-script lexical scope and execution position; no new runtime script tag', 'runtime contract preserves lexical scope and classic script');
assert.equal(moduleRecord.byte_length, moduleBytes.length, 'manifest module byte length matches');
assert.equal(moduleRecord.sha256, crypto.createHash('sha256').update(moduleBytes).digest('hex'), 'manifest module SHA-256 matches');
assert.equal(fragmentRecord.byte_length, Buffer.byteLength(fragment), 'manifest fragment byte length matches');
assert.equal(fragmentRecord.sha256, crypto.createHash('sha256').update(fragment).digest('hex'), 'manifest fragment SHA-256 matches');
const reconstructed = fragment.replace(marker, moduleText);
assert.ok(reconstructed.includes('function getQuizPool(){'), 'reconstructed fragment contains base candidate pool function');
assert.ok(reconstructed.includes('const __aniEmqGetQuizPoolBaseV8248=getQuizPool;getQuizPool=function(){'), 'reconstructed fragment preserves adjacent combiner/audio/custom-list wrapper');
assert.ok(reconstructed.indexOf('function getQuizPool(){') < reconstructed.indexOf('const __aniEmqGetQuizPoolBaseV8248=getQuizPool;'), 'base function executes before wrapper capture');
assert.equal(reconstructed.includes(marker), false, 'reconstruction has no unresolved pool marker');
assert.equal(moduleText.endsWith('return scoped};'), true, 'module ends at the exact wrapper boundary before updateQuizCounts');
const template = fs.readFileSync(path.join(root, 'src/template.html.in'), 'utf8');
assert.equal((template.match(/AMQ_SPLIT_FRAGMENT:script:004/g) || []).length, 1, 'template still has exactly one script_004 fragment marker');
console.log('PASS getQuizPool exact extraction contract');
console.log('assertions=16 module_bytes=' + moduleBytes.length + ' module_sha256=' + crypto.createHash('sha256').update(moduleBytes).digest('hex'));
console.log('LIMITATION release byte-identity is additionally asserted by tools/verify.py; runtime behavior by candidate_pool_integration.test.cjs');
