'use strict';
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const fragmentPath = path.join(root, 'src/scripts/script_004.htmlpart');
const modulePath = path.join(root, 'src/modules/quiz_suggestion_renderer.js');
const manifestPath = path.join(root, 'reports/FRAGMENT_MANIFEST.json');
const controllerPath = path.join(root, 'src/modules/quiz_suggestion_controller.js');
const sha256 = (b) => crypto.createHash('sha256').update(b).digest('hex');
const fragment = fs.readFileSync(fragmentPath);
const moduleBytes = fs.readFileSync(modulePath);
const controllerBytes = fs.readFileSync(controllerPath);
const getQuizPoolBytes = fs.readFileSync(path.join(root, 'src/modules/get_quiz_pool.htmlpart'));
const getQuizPoolMarker = Buffer.from('<!-- AMQ_SPLIT_MODULE:get_quiz_pool -->');
const marker = Buffer.from('<!-- AMQ_SPLIT_MODULE:quiz_suggestion_renderer -->');
const controllerMarker = Buffer.from('<!-- AMQ_SPLIT_MODULE:quiz_suggestion_controller -->');
const moduleSha256 = 'b65d52d0d0b4c384d789c6f16ddbcd42b505a84963ff27af7e278006a9ebfe21';
assert.equal(fragment.toString('utf8').split(marker.toString()).length - 1, 1, 'exactly one renderer module marker');
assert.equal(fragment.toString('utf8').split(controllerMarker.toString()).length - 1, 1, 'exactly one controller module marker');
assert.equal(moduleBytes.length, 3338, 'renderer module byte length matches captured source');
assert.equal(sha256(moduleBytes), moduleSha256, 'renderer module matches captured source fingerprint');
assert.equal(fragment.toString('utf8').split(controllerMarker.toString()).length - 1, 1, 'controller marker remains uniquely placed');
assert.equal(fragment.toString('utf8').split(getQuizPoolMarker.toString()).length - 1, 1, 'getQuizPool marker remains uniquely placed');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const getQuizPoolRecord = manifest.modules.find((x) => x.name === 'get_quiz_pool');
assert.ok(getQuizPoolRecord, 'getQuizPool module remains registered');
assert.equal(getQuizPoolRecord.byte_length, getQuizPoolBytes.length, 'getQuizPool module byte length matches manifest');
assert.equal(getQuizPoolRecord.sha256, sha256(getQuizPoolBytes), 'getQuizPool module fingerprint matches manifest');
assert.ok(getQuizPoolBytes.includes(Buffer.from('function calculateQuizPoolCandidatesV8280(ctx){')), 'getQuizPool module exposes the pure calculator boundary');
const source = moduleBytes.toString('utf8');
assert.ok(source.startsWith('function renderQuizSuggestionLabelV824('), 'module starts at renderer function boundary');
assert.ok(source.includes('function buildSuggestions(){'), 'module contains production buildSuggestions renderer');
assert.ok(source.includes('while(low<high)'), 'bounded top-25 insertion ordering is retained');
assert.ok(source.includes("b.addEventListener('click',()=>chooseQuizSuggestion(item.label))"), 'selection still delegates to the shared selection contract');
assert.ok(source.includes("input.setAttribute('aria-expanded',String(open))"), 'renderer retains combobox expanded-state update');
const record = manifest.modules.find((x) => x.name === 'quiz_suggestion_renderer');
assert.ok(record, 'manifest registers renderer module');
assert.equal(record.byte_length, moduleBytes.length, 'manifest byte length matches module');
assert.equal(record.sha256, sha256(moduleBytes), 'manifest SHA-256 matches module');
assert.equal(manifest.module_count, manifest.modules.length, 'manifest module count is consistent');
console.log('PASS quiz suggestion renderer extraction contract');
console.log(`assertions=15 module_bytes=${moduleBytes.length} script_004_bytes=${fragment.length}`);
